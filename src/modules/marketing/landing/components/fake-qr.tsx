import { LogoMark } from '@/shared/components/brand/logo'
import { cn } from '@/shared/lib/utils'

const SIZE = 25

/** Deterministic pseudo-random modules so server and client render the same pattern. */
function buildModules(seed: number) {
  let s = seed
  const rand = () => {
    s = (s * 1664525 + 1013904223) % 4294967296
    return s / 4294967296
  }
  const inFinder = (x: number, y: number) =>
    (x < 8 && y < 8) || (x >= SIZE - 8 && y < 8) || (x < 8 && y >= SIZE - 8)
  const inLogo = (x: number, y: number) => x >= 9 && x <= 15 && y >= 9 && y <= 15

  const cells: Array<[number, number]> = []
  for (let y = 0; y < SIZE; y++) {
    for (let x = 0; x < SIZE; x++) {
      if (inFinder(x, y) || inLogo(x, y)) continue
      if (rand() > 0.52) cells.push([x, y])
    }
  }
  return cells
}

function Finder({ x, y }: { x: number; y: number }) {
  return (
    <g>
      <rect x={x} y={y} width="7" height="7" className="fill-ink" />
      <rect x={x + 1} y={y + 1} width="5" height="5" className="fill-white" />
      <rect x={x + 2} y={y + 2} width="3" height="3" className="fill-ink" />
    </g>
  )
}

/**
 * Decorative QR code for product mock-ups only — it is not scannable.
 * Real table QR codes are generated by Module 10.
 */
export function FakeQr({ seed = 7, className }: { seed?: number; className?: string }) {
  const cells = buildModules(seed)
  return (
    <div aria-hidden className={cn('relative aspect-square', className)}>
      <svg viewBox={`0 0 ${SIZE} ${SIZE}`} className="size-full" shapeRendering="crispEdges">
        <rect width={SIZE} height={SIZE} className="fill-white" />
        {cells.map(([x, y]) => (
          <rect key={`${x}-${y}`} x={x} y={y} width="1" height="1" className="fill-ink" />
        ))}
        <Finder x={0} y={0} />
        <Finder x={SIZE - 7} y={0} />
        <Finder x={0} y={SIZE - 7} />
      </svg>
      <LogoMark tile title="" className="absolute top-1/2 left-1/2 size-[22%] -translate-x-1/2 -translate-y-1/2 rounded-[22%] ring-2 ring-white" />
    </div>
  )
}
